use crate::AddressingMode;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Opcode {
    pub code: u8,
    pub bytes: u8,
    pub base_cycles: u8,
    pub mode: AddressingMode,
    pub official: bool,
}

#[derive(Clone, Copy)]
pub(crate) struct OpcodeDefinition {
    pub(crate) base_cycles: u8,
    pub(crate) mode: AddressingMode,
    pub(crate) official: bool,
    pub(crate) indexed_read_page_penalty: bool,
}

const fn opcode_definition(
    base_cycles: u8,
    mode: AddressingMode,
    official: bool,
    indexed_read_page_penalty: bool,
) -> OpcodeDefinition {
    OpcodeDefinition {
        base_cycles,
        mode,
        official,
        indexed_read_page_penalty,
    }
}

macro_rules! op {
    ($cycles:literal, $mode:ident, $official:literal, $page_cross:literal) => {
        opcode_definition($cycles, AddressingMode::$mode, $official, $page_cross)
    };
}

