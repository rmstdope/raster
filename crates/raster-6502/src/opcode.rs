pub fn opcode(byte: u8) -> Opcode {
    let definition = definition(byte);
    Opcode {
        code: byte,
        bytes: definition.mode.operand_bytes() + 1,
        base_cycles: definition.base_cycles,
        mode: definition.mode,
        official: definition.official,
    }
}

pub(crate) const fn definition(byte: u8) -> OpcodeDefinition {
    OPCODES[byte as usize]
}
